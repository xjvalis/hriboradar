/** Great-circle-ish (lat/lon Euclidean, longitude corrected) nearest match - good enough at this scale, matches the same approximation leafletHtml.ts uses for its own IDW interpolation. */
export function nearestTouristArea(lat: number, lon: number): TouristArea {
  let best = TOURIST_AREAS[0];
  let bestDist = Infinity;
  for (const area of TOURIST_AREAS) {
    const dlat = area.lat - lat;
    const dlon = (area.lon - lon) * 0.66;
    const d = dlat * dlat + dlon * dlon;
    if (d < bestDist) {
      bestDist = d;
      best = area;
    }
  }
  return best;
}
